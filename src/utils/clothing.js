const RULES = [
  [28, ['민소매', '반팔', '반바지', '린넨 옷', '모자', '선크림']],
  [23, ['반팔', '얇은 셔츠', '면바지']],
  [20, ['얇은 긴팔', '가디건', '면바지']],
  [17, ['맨투맨', '얇은 니트', '가디건', '청바지']],
  [12, ['자켓', '트렌치코트', '니트']],
  [9, ['트렌치코트', '야상', '니트', '레이어드']],
  [5, ['코트', '히트텍', '니트']],
  [-Infinity, ['패딩', '두꺼운 코트', '목도리', '장갑']],
]

export function clothing(temp, rainy) {
  const items = RULES.find(([min]) => temp >= min)[1]
  return rainy ? [...items, '우산 또는 방수 자켓'] : items
}
